// Log output: the game's localized strings are single-byte Windows code-page text (Windows-1250 for Polish and Czech,
// 1251 for Russian, 1252 otherwise); stdout logs are UTF-8. openiw2 tooling only, not game behaviour.
#pragma once

#include <cstdint>
